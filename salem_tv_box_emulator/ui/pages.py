class PerformancePage(Page):
    def __init__(self) -> None:
        super().__init__("Performance & network")
        self.summary = label("No profile loaded.", "muted")
        self.body.addWidget(self.summary)
        form = QFormLayout()
        form.setSpacing(16)
        self.ram = QSpinBox()
        self.ram.setRange(1024, 8192)
        self.ram.setSingleStep(512)
        self.ram.setValue(2048)
        self.ram.setSuffix(" MB")
        self.cpus = QSpinBox()
        self.cpus.setRange(1, 8)
        self.cpus.setValue(2)
        self.gpu = QCheckBox("Use host GPU")
        self.gpu.setChecked(True)
        form.addRow("Memory", self.ram)
        form.addRow("CPU cores", self.cpus)
        form.addRow("Graphics", self.gpu)
        self.body.addLayout(form)
        self.apply = button("Optimize Emulator Performance", "primary", QStyle.StandardPixmap.SP_DialogApplyButton)
        self.body.addWidget(self.apply)
        self.status = label("Stop Google TV before changing performance settings.", "muted")
        self.body.addWidget(self.status)
        network = self.section("Network")
        self.network = button("Check Network", icon=QStyle.StandardPixmap.SP_BrowserReload)
        self.output = QPlainTextEdit()
        self.output.setReadOnly(True)
        self.output.setMinimumHeight(200)
        network.addWidget(self.network)
        network.addWidget(self.output)
        self.body.addStretch()
