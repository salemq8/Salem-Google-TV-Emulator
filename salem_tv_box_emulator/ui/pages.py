"""Launcher and control pages. The coordinating window connects their actions."""
from PySide6.QtCore import Qt
from PySide6.QtWidgets import QBoxLayout, QCheckBox, QFormLayout, QLineEdit, QPlainTextEdit, QSpinBox, QStyle, QVBoxLayout, QWidget

from .components import Page, RemotePad, app_logo, button, label, row


class HomePage(Page):
    def __init__(self) -> None:
        super().__init__("Google TV", "Salem Google TV Emulator")
        self.state = label("Checking engine...", "status")
        self.serial = label("No active device", "muted")
        self.body.addLayout(row(app_logo(72), self.state))
        self.body.addWidget(self.serial)
        self.launch = button("Launch Google TV", "primary", QStyle.StandardPixmap.SP_MediaPlay)
        self.stop = button("Stop", "danger", QStyle.StandardPixmap.SP_MediaStop)
        self.restart = button("Restart", icon=QStyle.StandardPixmap.SP_BrowserReload)
        self.body.addLayout(row(self.launch, self.restart, self.stop))
        display = self.section("Display")
        self.tv_status = label("TV Mode off", "muted")
        self.enter_tv = button("Enter TV Mode", icon=QStyle.StandardPixmap.SP_TitleBarMaxButton)
        self.exit_tv = button("Exit TV Mode", icon=QStyle.StandardPixmap.SP_TitleBarNormalButton)
        display.addWidget(self.tv_status)
        display.addLayout(row(self.enter_tv, self.exit_tv))
        quick = self.section("Controls")
        self.remote = button("Remote", icon=QStyle.StandardPixmap.SP_ComputerIcon)
        self.popout = button("Pop-out Remote", icon=QStyle.StandardPixmap.SP_TitleBarNormalButton)
        quick.addLayout(row(self.remote, self.popout))
        engine = self.section("Engine")
        self.engine_status = label("Checking installed tools...", "muted")
        self.repair = button("Fix Everything & Launch", icon=QStyle.StandardPixmap.SP_BrowserReload)
        self.install = button("Install APK", icon=QStyle.StandardPixmap.SP_DialogOpenButton)
        engine.addWidget(self.engine_status)
        engine.addLayout(row(self.repair, self.install))
        self.activity = label("Ready when you are.", "muted")
        self.body.addStretch()
        self.body.addWidget(self.activity)


class ControlsPage(Page):
    def __init__(self) -> None:
        super().__init__("Remote & input")
        self.serial = label("No active device", "muted")
        self.popout = button("Pop-out Remote", icon=QStyle.StandardPixmap.SP_TitleBarNormalButton)
        self.body.addLayout(row(self.serial, self.popout))
        self.pad = RemotePad()
        self.columns = QBoxLayout(QBoxLayout.Direction.LeftToRight)
        self.columns.setSpacing(28)
        self.columns.addWidget(self.pad, 0, Qt.AlignmentFlag.AlignTop | Qt.AlignmentFlag.AlignHCenter)
        input_panel = QWidget()
        text = QVBoxLayout(input_panel)
        text.setContentsMargins(0, 16, 0, 0)
        text.setSpacing(16)
        text.addWidget(label("Send Text to TV", "section"))
        self.text = QLineEdit()
        self.text.setPlaceholderText("English / العربية")
        self.text.setAccessibleName("Send Text to TV")
        self.send = button("Send", "primary", QStyle.StandardPixmap.SP_ArrowForward)
        text.addLayout(row(self.text, self.send))
        self.text_status = label("No text sent yet.", "muted")
        text.addWidget(self.text_status)
        text.addSpacing(20)
        text.addWidget(label("Audio", "section"))
        self.audio_status = label("Audio uses the emulator's default backend.", "muted")
        text.addWidget(self.audio_status)
        text.addWidget(label("Test Sound sets the TV media volume to 10. Audible playback depends on the active TV app.", "muted"))
        text.addStretch()
        self.columns.addWidget(input_panel, 1)
        self.body.addLayout(self.columns)
        self.body.addStretch()

    def resizeEvent(self, event) -> None:
        self.columns.setDirection(QBoxLayout.Direction.LeftToRight if self.width() >= 780 else QBoxLayout.Direction.TopToBottom)
        super().resizeEvent(event)


